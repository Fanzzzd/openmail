export const START = "{/* mcp-tools:start. Generated by apps/docs/scripts/mcp-tools.ts. */}";
export const END = "{/* mcp-tools:end */}";

/** A Markdown table padded the way oxfmt writes it, so the page passes the format check. */
function table(tools: typeof MCP_TOOLS): string[] {
  const rows = [
    ["Tool", "What it does", "Read-only"],
    ...tools.map((tool) => [
      `\`${tool.name}\``,
      TOOL_SUMMARIES[tool.name],
      tool.readOnly ? "Yes" : "No",
    ]),
  ];
  const widths = rows[0]!.map((_, column) =>
    Math.max(3, ...rows.map((row) => row[column]!.length)),
  );
  const line = (cells: string[]) =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column]!)).join(" | ")} |`;
  return [
    line(rows[0]!),
    line(widths.map((width) => "-".repeat(width))),
    ...rows.slice(1).map(line),
  ];
}

export function renderToolTables(): string {
  const offered = MCP_TOOLS.filter((tool) => tool.default);
  const proposals = MCP_TOOLS.filter((tool) => !tool.default);
  return [
    START,
    "",
    `By default the server offers ${offered.length} tools:`,
    "",
    ...table(offered),
    "",
    `With write access turned on, the server adds ${proposals.length} write tools:`,
    "",
    ...table(proposals),
    "",
    END,
  ].join("\n");
}

/** The page with its generated block replaced. */
export function withToolTables(page: string): string {
  const start = page.indexOf(START);
  const end = page.indexOf(END);
  if (start < 0 || end < start) throw new Error("cli-and-mcp.mdx has no mcp-tools markers");
  return page.slice(0, start) + renderToolTables() + page.slice(end + END.length);
}
